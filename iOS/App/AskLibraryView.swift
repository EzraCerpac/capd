import CapdAnswers
import CapdDesignSystem
import CapdMobile
import SwiftUI

struct AskLibraryView: View {
    let library: LibraryModel
    @Environment(\.dismiss) private var dismiss
    @Environment(\.scenePhase) private var scenePhase
    @State private var session = AnswerSession(model: answerModel(), retriever: localRetriever)
    @FocusState private var questionFocused: Bool

    var body: some View {
        NavigationStack {
            Form {
                #if DEBUG && targetEnvironment(simulator)
                    if ProcessInfo.processInfo.arguments.contains("--capd-synthetic-citation") {
                        Text(
                            "Synthetic citation test — generated by a fixture, not Apple Intelligence."
                        )
                        .font(.footnote)
                    }
                #endif
                Section("Ask your saved sources") {
                    TextField(
                        "What would you like to know?", text: $session.question, axis: .vertical
                    )
                    .lineLimit(2...6).submitLabel(.send)
                    .accessibilityIdentifier("libraryQuestion")
                    .focused($questionFocused)
                    .onSubmit { session.ask() }
                    if session.isAnswering {
                        HStack {
                            ProgressView()
                            Text("Reading matching saved text…")
                            Spacer()
                            Button("Cancel") { session.cancel() }
                        }.accessibilityIdentifier("cancelLibraryQuestion")
                    } else {
                        Button("Ask Cap", systemImage: "sparkles") {
                            questionFocused = false
                            session.ask()
                        }
                        .disabled(
                            session.availability != .available
                                || session.question
                                    .trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
                        )
                        .accessibilityIdentifier("askLibraryQuestion")
                    }
                }
                if case .unavailable(let reason) = session.availability {
                    Section("Apple Intelligence") {
                        Text(reason.explanation)
                        Button("Check again") { session.refreshAvailability() }
                            .accessibilityIdentifier("checkAnswerAvailability")
                    }
                }
                if let message = session.message {
                    Section { Text(message).accessibilityIdentifier("libraryAnswerMessage") }
                }
                if let answer = session.answer {
                    Section("Answer") {
                        ForEach(Array(answer.statements.enumerated()), id: \.offset) {
                            _, statement in
                            VStack(alignment: .leading, spacing: 8) {
                                Text(statement.text).textSelection(.enabled)
                                Text(
                                    statement.citations.map { "[\($0.number)]" }.joined(
                                        separator: " ")
                                )
                                .font(.caption).foregroundStyle(.secondary)
                            }
                        }
                    }.accessibilityIdentifier("libraryAnswer")
                    Section("Supporting sources") {
                        ForEach(answer.sources, id: \.number) { source in
                            VStack(alignment: .leading, spacing: 8) {
                                if let id = UUID(uuidString: source.source.id) {
                                    NavigationLink {
                                        CaptureDetailView(captureID: id, model: library)
                                            .onAppear { library.reload() }
                                    } label: {
                                        Text("[\(source.number)] \(source.source.title)")
                                    }
                                    .accessibilityIdentifier("answerSource-\(source.number)")
                                }
                                ForEach(quotes(for: source.number, in: answer), id: \.self) {
                                    quote in
                                    Text("“\(quote)”").font(.subheadline).textSelection(.enabled)
                                }
                            }
                        }
                        Text(
                            "Answers can be mistaken. Check the supporting text. Sources open their current saved version."
                        )
                        .font(.footnote).foregroundStyle(.secondary)
                    }
                }
                Section {
                    Text(
                        "Questions and answers stay on this device and are not saved. Cap uses matching text already saved here, including downloaded page text. It does not fetch links or use a remote AI service."
                    )
                    .font(.footnote).foregroundStyle(.secondary)
                }
            }
            .capdCanvas()
            .navigationTitle("Ask Cap").navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItemGroup(placement: .keyboard) {
                    Spacer()
                    Button("Done") { questionFocused = false }
                        .accessibilityIdentifier("dismissQuestionKeyboard")
                }
                ToolbarItem(placement: .cancellationAction) { Button("Done") { dismiss() } }
            }
            .onAppear { session.refreshAvailability() }
            .onChange(of: session.question) { _, _ in session.questionChanged() }
            .onChange(of: scenePhase) { _, phase in
                if phase == .active { session.refreshAvailability() } else { session.cancel() }
            }
            .onDisappear { session.cancel() }
        }.capdCanvas()
    }

    private func quotes(for number: Int, in answer: GroundedAnswer) -> [String] {
        var seen = Set<String>()
        return answer.statements.flatMap(\.citations).filter { $0.number == number }
            .map(\.quote).filter { seen.insert($0).inserted }
    }

    // Create a reader only after the user asks; do not initialize a writer or run
    // store migrations as part of answering. This shares the existing app-group path.
    nonisolated private static func localRetriever() async throws -> any AnswerRetrieving {
        let container = try MobileEnvironment.root()
        let selected = try MobileLibraryAccess.selected(in: container)
        return try MobileAnswerRetrieval(
            databaseURL: selected.databaseURL(in: container),
            access: MobileLibraryAccess(root: container, configuration: selected))
    }

    nonisolated private static func answerModel() -> any AnswerGenerating {
        #if DEBUG && targetEnvironment(simulator)
            if ProcessInfo.processInfo.arguments.contains("--capd-synthetic-citation") {
                return SyntheticCitationModel()
            }
        #endif
        return OnDeviceAnswerModel()
    }
}

#if DEBUG && targetEnvironment(simulator)
    private struct SyntheticCitationModel: AnswerGenerating {
        func availability() -> AnswerAvailability { .available }

        func answer(question: String, sources: [NumberedEvidence]) async throws -> AnswerDraft {
            let quote = "An orchid needs indirect light."
            guard
                let source = sources.first(where: {
                    $0.source.excerpt.contains(quote)
                        && $0.source.excerpt.contains("synthetic gardening evidence")
                })
            else { throw AnswerError.insufficientEvidence }
            return AnswerDraft(statements: [
                .init(
                    text: "The synthetic orchid needs indirect light.",
                    citations: [.init(number: source.number, quote: quote)])
            ])
        }
    }
#endif
